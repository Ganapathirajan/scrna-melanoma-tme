def get_uniprot_and_pdb(gene_name, organism_id='9606'):
    """
    Query UniProt for human protein ID and associated PDB structures.
    9606 = Homo sapiens taxonomy ID
    """
    # Search UniProt
    url = f"https://rest.uniprot.org/uniprotkb/search"
    params = {
        'query': f'gene_exact:{gene_name} AND organism_id:{organism_id} AND reviewed:true',
        'format': 'json',
        'fields': 'accession,gene_names,protein_name,xref_pdb',
        'size': 1
    }
    try:
        r = requests.get(url, params=params, timeout=10)
        data = r.json()
        if data['results']:
            entry = data['results'][0]
            uniprot_id = entry['primaryAccession']
            # Extract PDB IDs
            pdb_ids = []
            for ref in entry.get('uniProtKBCrossReferences', []):
                if ref['database'] == 'PDB':
                    pdb_ids.append(ref['id'])
            return uniprot_id, pdb_ids[:3]  # Return top 3 PDB structures
        return None, []
    except Exception as e:
        print(f"  Error for {gene_name}: {e}")
        return None, []

