import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import (classification_report,
    roc_auc_score, confusion_matrix, roc_curve)
import scipy.sparse as sp
import warnings
warnings.filterwarnings("ignore")

# ── Select HVGs for ML features ───────────────────────────────
import scanpy as sc
sc.pp.highly_variable_genes(adata, n_top_genes=2000)
hvg_names = adata.var_names[adata.var["highly_variable"]].tolist()
print(f"HVGs selected : {len(hvg_names)}")

# ── Balanced subsample ────────────────────────────────────────
pd_idx  = adata.obs[adata.obs["condition"] == "PD"].index
ct_idx  = adata.obs[adata.obs["condition"] == "Control"].index
n_each  = min(4000, len(pd_idx), len(ct_idx))

rng      = np.random.default_rng(42)
pd_samp  = rng.choice(pd_idx, n_each, replace=False)
ct_samp  = rng.choice(ct_idx, n_each, replace=False)
keep     = np.concatenate([pd_samp, ct_samp])

sub = adata[keep, hvg_names].copy()
print(f"Subsampled    : {sub.n_obs:,} cells × {sub.n_vars:,} HVGs")
print(sub.obs["condition"].value_counts())

# ── Build X and y ─────────────────────────────────────────────
X = sub.X.toarray() if sp.issparse(sub.X) else sub.X.copy()
y = (sub.obs["condition"] == "PD").astype(int).values

# ── 5-fold cross validation ───────────────────────────────────
print("\nTraining Random Forest — 5-fold CV ...")
clf = RandomForestClassifier(
    n_estimators = 200,
    max_depth    = 15,
    random_state = 42,
    n_jobs       = -1
)

skf      = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
aucs, tprs, mean_fpr = [], [], np.linspace(0, 1, 100)

for fold, (tr, te) in enumerate(skf.split(X, y)):
    clf.fit(X[tr], y[tr])
    proba    = clf.predict_proba(X[te])[:, 1]
    auc      = roc_auc_score(y[te], proba)
    aucs.append(auc)
    fpr, tpr, _ = roc_curve(y[te], proba)
    tprs.append(np.interp(mean_fpr, fpr, tpr))
    print(f"  Fold {fold+1} AUC : {auc:.3f}")

print(f"\nMean AUC : {np.mean(aucs):.3f} ± {np.std(aucs):.3f}")

# ── ROC curve ─────────────────────────────────────────────────
mean_tpr    = np.mean(tprs, axis=0)
mean_tpr[0] = 0.0

fig, ax = plt.subplots(figsize=(6, 5))
ax.plot(mean_fpr, mean_tpr, color="#D85A30", lw=2,
    label=f"Mean ROC (AUC = {np.mean(aucs):.3f} ± {np.std(aucs):.3f})")
ax.fill_between(mean_fpr,
    np.mean(tprs, axis=0) - np.std(tprs, axis=0),
    np.mean(tprs, axis=0) + np.std(tprs, axis=0),
    alpha=0.2, color="#D85A30")
ax.plot([0,1],[0,1],"k--", lw=1, label="Random classifier")
ax.set_xlabel("False Positive Rate")
ax.set_ylabel("True Positive Rate")
ax.set_title("ROC Curve — PD vs Control Classifier\n(Random Forest, 5-fold CV)")
ax.legend(loc="lower right")
plt.tight_layout()
plt.savefig("/content/data/roc_curve.png", dpi=150)
plt.show()

# Train final model on full subset
print("Training final model ...")
clf.fit(X, y)

importances = pd.Series(
    clf.feature_importances_,
    index=hvg_names
).sort_values(ascending=False)

top20 = importances.head(20)

fig, ax = plt.subplots(figsize=(8, 6))
colors  = ["#D85A30"] * 5 + ["#185FA5"] * 15
top20[::-1].plot(kind="barh", ax=ax,
    color=colors[::-1])
ax.set_xlabel("Feature Importance")
ax.set_title("Top 20 Genes — PD vs Control\nRandom Forest Classifier")
ax.axvline(importances.mean(), color="gray",
    linestyle="--", lw=1, label="Mean importance")
ax.legend()
plt.tight_layout()
plt.savefig("/content/data/feature_importance.png", dpi=150)
plt.show()

print("\nTop 10 genes:")
print(top20.head(10).round(5).to_string())

# Final predictions
y_pred = clf.predict(X)
cm     = confusion_matrix(y, y_pred)

fig, ax = plt.subplots(figsize=(5, 4))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
    xticklabels=["Control","PD"],
    yticklabels=["Control","PD"], ax=ax)
ax.set_xlabel("Predicted")
ax.set_ylabel("Actual")
ax.set_title("Confusion Matrix — PD vs Control")
plt.tight_layout()
plt.savefig("/content/data/confusion_matrix.png", dpi=150)
plt.show()

print(classification_report(y, y_pred,
    target_names=["Control","PD"]))

