def get_smiles(compound_name):
    url = f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/name/{compound_name}/property/IsomericSMILES,MolecularWeight,MolecularFormula/JSON"
    try:
        r = requests.get(url, timeout=10)
        data = r.json()
        prop = data['PropertyTable']['Properties'][0]
        return {
            'compound': compound_name,
            'smiles': prop.get('IsomericSMILES', ''),
            'mol_weight': prop.get('MolecularWeight', ''),
            'formula': prop.get('MolecularFormula', '')
        }
    except:
        return {'compound': compound_name, 'smiles': None, 'mol_weight': None, 'formula': None}

