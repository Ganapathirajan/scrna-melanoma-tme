# ── Step 2: Read UMI in chunks → build sparse matrix ──────────
# Never loads full matrix into RAM
# Each chunk = 500 genes at a time → ~200 MB per chunk max
print("\nLoading UMI matrix in chunks (genes x cells) ...")
print("This will take 3-6 minutes but will NOT crash ...")

CHUNK_SIZE = 500   # genes per chunk — reduce to 200 if still slow

chunks      = []   # list of sparse matrices, one per chunk
gene_names  = []   # gene row index collected as we go
cell_names  = None # column names (cell barcodes) — read once

reader = pd.read_csv(
    UMI_PATH,
    sep       = "\t",
    index_col = 0,
    chunksize = CHUNK_SIZE,
    dtype     = np.float32   # float32 uses half the RAM of float64
)

total_genes_loaded = 0
for i, chunk in enumerate(reader):

    # Capture cell barcode names from first chunk only
    if cell_names is None:
        cell_names = chunk.columns.tolist()
        print(f"  Cell barcodes found : {len(cell_names)}")

    # Convert dense chunk → sparse immediately (before stacking)
    sparse_chunk = sp.csr_matrix(chunk.values)
    chunks.append(sparse_chunk)
    gene_names.extend(chunk.index.tolist())

    total_genes_loaded += chunk.shape[0]

    # Progress every 5 chunks
    if (i + 1) % 5 == 0:
        print(f"  Loaded {total_genes_loaded:,} / ~26,737 genes ...", flush=True)

# Stack all sparse chunks vertically → full genes x cells matrix
print("\nStacking chunks into full sparse matrix ...")
X_genes_x_cells = sp.vstack(chunks)          # shape: genes x cells
print(f"  Full shape (genes x cells) : {X_genes_x_cells.shape}")

# Transpose → cells x genes (AnnData format)
X_cells_x_genes = X_genes_x_cells.T.tocsr()
print(f"  Transposed (cells x genes) : {X_cells_x_genes.shape}")

